target = 'Revenue'

categorical_cols = [
    'Month', 'OperatingSystems', 'Browser',
    'Region', 'TrafficType', 'VisitorType',
    'Weekend'
]

numeric_cols = [
    col for col in data.columns
    if col not in categorical_cols + [target]
]


X = data.drop(columns=target)
y = data[target]

preprocessor_binary = ColumnTransformer(
    transformers=[
        ('numeric', KBinsDiscretizer(
            n_bins=4,
            encode='onehot-dense',
            strategy='uniform'
        ), numeric_cols),

        ('categorical', OneHotEncoder(
            handle_unknown='ignore',
            sparse_output=False
        ), categorical_cols)
    ],
    sparse_threshold=0
)

categorical_encoder = Pipeline([
    ('encoder', OrdinalEncoder(
        handle_unknown='use_encoded_value',
        unknown_value=-1
    )),
    ('shift', FunctionTransformer(
        lambda x: x + 1
    ))
])

preprocessor_discrete = ColumnTransformer(
    transformers=[
        ('numeric', KBinsDiscretizer(
            n_bins=5,
            encode='ordinal',
            strategy='uniform'
        ), numeric_cols),

        ('categorical', categorical_encoder, categorical_cols)
    ],
    sparse_threshold=0
)

preprocessor_mixed = ColumnTransformer(
    transformers=[
        ('numeric', StandardScaler(), numeric_cols),

        ('categorical', OneHotEncoder(
            handle_unknown='ignore',
            sparse_output=False
        ), categorical_cols)
    ],
    sparse_threshold=0
)

def get_full_binary_pipeline():
    return Pipeline([
        ('preprocessor', clone(preprocessor_binary))
    ])

def get_full_discrete_pipeline():
    return Pipeline([
        ('preprocessor', clone(preprocessor_discrete))
    ])

def get_mixed_pipeline():
    return Pipeline([
        ('preprocessor', clone(preprocessor_mixed))
    ])
    
